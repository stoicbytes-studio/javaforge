#!/usr/bin/env node
/**
 * Compiles every feature probe in src/content/versions/javaReleases.ts on
 * real JDKs (Docker images eclipse-temurin:<v>-jdk) and records, per JDK,
 * whether the feature is final (compiles normally), preview (compiles only
 * with --enable-preview) or absent. Writes src/content/versions/probes.generated.ts.
 *
 * Usage: node scripts/probe-java-versions.mjs   (requires Docker)
 */
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { JAVA_FEATURES, PROBED_JDKS } = await import(pathToFileURL(join(root, 'src/content/versions/javaReleases.ts')).href);
const [docker, ...dockerArgs] = (process.env.DOCKER ?? 'docker').split(' ');
const probes = JAVA_FEATURES.filter((f) => f.probe);

const work = mkdtempSync(join(tmpdir(), 'jf-probe-'));
for (const f of probes) {
  mkdirSync(join(work, f.id));
  writeFileSync(join(work, f.id, f.probe.fileName ?? 'Main.java'), f.probe.code);
}

// One container per JDK compiles every probe twice (plain, then with preview enabled).
const script = (v) => `
for d in /w/*/; do
  id=$(basename "$d"); src=$(ls "$d"*.java)
  out="/tmp/$id"; mkdir -p "$out"
  if javac -nowarn -d "$out" "$src" >/dev/null 2>&1; then echo "$id final";
  elif ${v >= 12 ? `javac -nowarn --release ${v} --enable-preview -d "$out" "$src" >/dev/null 2>&1` : 'false'}; then echo "$id preview";
  else echo "$id absent"; fi
done`;

const results = {};
for (const v of PROBED_JDKS) {
  const r = spawnSync(docker, [...dockerArgs, 'run', '--rm', '--network', 'none', '-e', 'JAVA_TOOL_OPTIONS=', '-v', `${work}:/w:ro`, `eclipse-temurin:${v}-jdk`, 'sh', '-c', script(v)], {
    encoding: 'utf8',
  });
  if (r.status !== 0) {
    console.error(`JDK ${v} failed:\n${r.stderr ?? r.error}`);
    process.exit(1);
  }
  for (const line of r.stdout.trim().split('\n')) {
    const [id, status] = line.split(' ');
    (results[id] ??= {})[v] = status;
  }
  console.log(`JDK ${v}: probed ${probes.length} features`);
}
rmSync(work, { recursive: true, force: true });

const body = `// GENERATED by scripts/probe-java-versions.mjs — do not edit by hand.
// Result of compiling each feature probe on real JDKs (Eclipse Temurin images).

export type ProbeStatus = 'final' | 'preview' | 'absent';

export const PROBE_GENERATED_AT = '${new Date().toISOString().slice(0, 10)}';

export const PROBE_RESULTS: Record<string, Record<number, ProbeStatus>> = ${JSON.stringify(results, null, 2)};
`;
writeFileSync(join(root, 'src/content/versions/probes.generated.ts'), body);
console.log('Wrote src/content/versions/probes.generated.ts');
