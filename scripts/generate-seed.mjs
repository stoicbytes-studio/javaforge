#!/usr/bin/env node
/**
 * Mirrors the bundled curriculum into the public content tables.
 *
 * Usage: npm run seed:generate            -> writes supabase/seed.sql
 *        node scripts/generate-seed.mjs -  -> prints to stdout
 *
 * The script replaces all public content in one transaction. It only touches
 * public tables; private learning records reference content by id without
 * foreign keys, so they survive content releases. Run the output with a
 * privileged connection (the Supabase CLI applies supabase/seed.sql on
 * `supabase db reset`); API roles cannot write content tables.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.ts') && !p.endsWith('index.ts') ? [p] : [];
  });
}

const load = async (file) => Object.values(await import(pathToFileURL(file).href));
const isModule = (v) => v && typeof v === 'object' && !Array.isArray(v) && Array.isArray(v.lessons) && typeof v.order === 'number';
const isChallenge = (v) => v && typeof v === 'object' && Array.isArray(v.tests) && typeof v.solution === 'string';

const modules = new Map();
const challenges = [];
let questions = [];
const concepts = {};
const memory = {};
const extraLessons = [];
for (const file of walk(contentDir)) {
  if (file.includes(`${join('content', 'concepts')}`)) {
    // Concept pages are keyed by lesson id and attached below.
    for (const value of await load(file)) if (value && typeof value === 'object') Object.assign(concepts, value);
    continue;
  }
  if (file.includes(`${join('content', 'memory')}`)) {
    // "Make it stick" memory aids are keyed by lesson id too.
    for (const value of await load(file)) if (value && typeof value === 'object') Object.assign(memory, value);
    continue;
  }
  for (const value of await load(file)) {
    const items = Array.isArray(value) ? value : [value];
    for (const item of items) {
      // Written modules override their "planned" outline entries.
      if (isModule(item) && (!modules.has(item.id) || item.lessons.length > 0)) modules.set(item.id, item);
      else if (isChallenge(item)) challenges.push(item);
      else if (item && typeof item === 'object' && Array.isArray(item.checks) && item.moduleId && (file.endsWith('-more.ts') || file.includes(join('modules', 'extra')))) extraLessons.push(item);
    }
    if (file.includes(join('content', 'interview')) && Array.isArray(value)) questions = [...questions, ...value];
  }
}
const { ACHIEVEMENTS } = await import(pathToFileURL(join(root, 'src', 'features', 'gamification', 'achievements.ts')).href);

const text = (s) => (s === undefined || s === null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const json = (v) => {
  const body = JSON.stringify(v);
  if (body.includes('$jf$')) throw new Error('content contains the dollar-quote tag $jf$');
  return `$jf$${body}$jf$::jsonb`;
};
const textArray = (a) => `array[${a.map(text).join(', ')}]::text[]`;

// Lessons kept in companion files (e.g. 03-oop-more.ts) belong to their module.
for (const l of extraLessons) {
  const m = modules.get(l.moduleId);
  if (m && !m.lessons.some((x) => x.id === l.id)) modules.set(m.id, { ...m, lessons: [...m.lessons, l] });
}
for (const [id, m] of modules) {
  modules.set(id, { ...m, lessons: m.lessons.map((l) => ({ ...l, ...(concepts[l.id] ? { concepts: concepts[l.id] } : {}), ...(memory[l.id] ? { memory: memory[l.id] } : {}) })) });
}
const sorted = [...modules.values()].sort((a, b) => a.order - b.order);
const lines = [
  '-- Generated by scripts/generate-seed.mjs from src/content. Do not edit by hand.',
  'begin;',
  'delete from public.modules;',
  'delete from public.achievements;',
];
for (const m of sorted) {
  const { lessons, ...meta } = m;
  lines.push(
    `insert into public.modules (id, position, title, short_title, summary, level, prerequisites, content) values (${text(m.id)}, ${m.order}, ${text(m.title)}, ${text(m.shortTitle)}, ${text(m.summary)}, ${text(m.level)}, ${textArray(m.prerequisites)}, ${json(meta)});`,
  );
  lessons.forEach((l, i) => {
    lines.push(
      `insert into public.lessons (id, module_id, position, title, difficulty, estimated_minutes, content) values (${text(l.id)}, ${text(m.id)}, ${i}, ${text(l.title)}, ${text(l.difficulty)}, ${l.estimatedMinutes}, ${json(l)});`,
    );
  });
}
for (const c of challenges) {
  lines.push(
    `insert into public.challenges (id, module_id, lesson_id, kind, title, difficulty, content) values (${text(c.id)}, ${text(c.moduleId)}, ${text(c.lessonId)}, ${text(c.kind)}, ${text(c.title)}, ${text(c.difficulty)}, ${json(c)});`,
  );
}
for (const q of questions) {
  lines.push(
    `insert into public.interview_questions (id, module_id, kind, difficulty, content) values (${text(q.id)}, ${text(q.moduleId)}, ${text(q.kind)}, ${text(q.difficulty)}, ${json(q)});`,
  );
}
for (const a of ACHIEVEMENTS) {
  lines.push(`insert into public.achievements (id, title, requirement, category) values (${text(a.id)}, ${text(a.title)}, ${text(a.requirement)}, ${text(a.category)});`);
}
lines.push('commit;', '');

const sql = lines.join('\n');
const lessonCount = sorted.reduce((n, m) => n + m.lessons.length, 0);
const summary = `${sorted.length} modules, ${lessonCount} lessons, ${challenges.length} challenges, ${questions.length} interview questions, ${ACHIEVEMENTS.length} achievements`;
if (process.argv[2] === '-') {
  process.stdout.write(sql);
  console.error(summary);
} else {
  const out = join(root, 'supabase', 'seed.sql');
  writeFileSync(out, sql);
  console.log(`Wrote ${out}: ${summary}`);
}
